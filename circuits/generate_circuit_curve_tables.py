#!/usr/bin/env python3
"""Tabular version of the appendix faithfulness / completeness curves.

Reads <attribution-root>/*/circuit/graph.json for the 16 prompts used in the paper
(Jack + 15 appendix circuits) and writes:

  circuit_curves_per_prompt.csv   full F(n), C(n) for n = 0..50 for every prompt
  circuit_curves_tables.tex       two LaTeX tables (per-prompt summary, mean+-std grid)
  circuit_curves_tables.md        the same in markdown

Definitions (as in the paper):
  F(n) = P_circuit(n) / P_full   (add-back curve, graph.json["addback_curve"])
  C(n) = P_ablated(n) / P_full   (graph.json["faithfulness_curve"]; lower is better)
  n_F  = smallest circuit size with F >= 0.95
  n_C  = smallest circuit size with C <= 0.2
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics as st
from pathlib import Path

# Paper order (Fig. 1 prompt first, then appendix circuit figures).
TARGETS = ["eat", "hug", "chase", "prince", "voice", "day", "treasure", "table",
           "door", "read", "paper", "better", "mirror", "oven", "cry", "tall"]
F_THR, C_THR = 0.95, 0.20
GRID = [1, 2, 3, 5, 8, 10, 15, 20, 25, 30, 40, 50]


def load_all(root: Path):
    by_target = {}
    for p in sorted(root.glob("*/circuit/graph.json")):
        g = json.load(open(p, encoding="utf-8"))
        m = g["meta"]
        t = m["target_str"].strip()
        if t not in TARGETS or t in by_target:
            continue
        F = {int(round(x["n_added"])): x["retain_ratio"] for x in g["addback_curve"]}
        C = {int(x["n"]): x["faithfulness"] for x in g["faithfulness_curve"]}
        by_target[t] = dict(prompt=m["prompt"], target=t, p0=m["p0"], F=F, C=C)
    missing = [t for t in TARGETS if t not in by_target]
    if missing:
        raise SystemExit(f"missing prompts for targets: {missing}")
    return [by_target[t] for t in TARGETS]


def first(pred, rng):
    return next((n for n in rng if pred(n)), None)


def fmt(x, d=3):
    return "--" if x is None else f"{x:.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--attribution-root", type=Path,
                    default=Path("out/main_mlp_mult_32_K_8/attribution_graphs"))
    ap.add_argument("--out-dir", type=Path, default=None)
    a = ap.parse_args()
    out = (a.out_dir or a.attribution_root / "circuit_curves_table").resolve()
    out.mkdir(parents=True, exist_ok=True)
    rows = load_all(a.attribution_root.resolve())

    for r in rows:
        r["nF"] = first(lambda n: r["F"][n] >= F_THR, range(1, 51))
        r["nC"] = first(lambda n: r["C"][n] <= C_THR, range(1, 51))

    # ---- CSV with full curves
    with open(out / "circuit_curves_per_prompt.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["prompt", "target", "p0", "n", "F", "C"])
        for r in rows:
            for n in range(1, 51):
                w.writerow([r["prompt"], r["target"], f"{r['p0']:.4f}", n,
                            f"{r['F'][n]:.4f}", f"{r['C'][n]:.4f}"])

    # ---- Table A: per prompt
    hdr = ["Target", "$P_0$ (\\%)", "$n_F$", "$F(n_F)$", "$C(n_F)$", "$n_C$", "$F(20)$", "$C(20)$"]
    tex = ["% Auto-generated by generate_circuit_curve_tables.py",
           "\\begin{table*}[t!]", "\\centering", "\\small",
           "\\begin{tabular}{rlccccccc}", "\\toprule",
           "\\# & " + " & ".join(hdr) + " \\\\", "\\midrule"]
    md = ["| # | Target | P0 (%) | n_F | F(n_F) | C(n_F) | n_C | F(20) | C(20) |",
          "|--:|---|--:|--:|--:|--:|--:|--:|--:|"]
    for i, r in enumerate(rows, 1):
        nF, nC = r["nF"], r["nC"]
        cells = [str(i), f"\\texttt{{[{r['target']}]}}", f"{100*r['p0']:.1f}",
                 "--" if nF is None else str(nF),
                 fmt(r["F"][nF]) if nF else "--", fmt(r["C"][nF]) if nF else "--",
                 "--" if nC is None else str(nC), fmt(r["F"][20]), fmt(r["C"][20])]
        tex.append(" & ".join(cells) + " \\\\")
        md.append("| " + " | ".join(c.replace("\\texttt{[", "").replace("]}", "") for c in cells) + " |")
    def agg(vals):
        v = [x for x in vals if x is not None]
        return f"{st.mean(v):.3f} $\\pm$ {st.pstdev(v):.3f}"
    nFs = [r["nF"] for r in rows if r["nF"] is not None]
    nCs = [r["nC"] for r in rows if r["nC"] is not None]
    tex += ["\\midrule",
            f"\\multicolumn{{2}}{{l}}{{Median [min, max]}} & "
            f"{100*st.median([r['p0'] for r in rows]):.1f} & "
            f"{st.median(nFs):g} [{min(nFs)}, {max(nFs)}] & -- & -- & "
            f"{st.median(nCs):g} [{min(nCs)}, {max(nCs)}] & -- & -- \\\\",
            "\\bottomrule", "\\end{tabular}",
            "\\caption{\\textbf{Per-prompt circuit metrics.} $n_F$ is the smallest circuit size with "
            f"$F \\geq {F_THR}$ and $F(n_F)$, $C(n_F)$ are the metrics at that size; $n_C$ is the smallest size with "
            f"$C \\leq {C_THR}$; $F(20)$, $C(20)$ are the metrics at a fixed budget of 20 neurons. "
            "Entries marked -- are not reached within the 50-neuron beam-search budget. "
            "Row 1 is the circuit of Fig.~\\ref{fig:circuit}.}",
            "\\label{tab:circuit-per-prompt}", "\\end{table*}", ""]

    # ---- Table B: mean +- std over prompts on a grid of n
    def stat_row(key, fn):
        return [f"{fn([r[key][n] for r in rows]):.2f}" for n in GRID]
    tex += ["\\begin{table*}[t!]", "\\centering", "\\small", "\\setlength{\\tabcolsep}{4pt}",
            "\\begin{tabular}{l" + "c" * len(GRID) + "}", "\\toprule",
            "Neurons $n$ & " + " & ".join(map(str, GRID)) + " \\\\", "\\midrule",
            "$F$ mean & " + " & ".join(stat_row("F", st.mean)) + " \\\\",
            "$F$ std & " + " & ".join(stat_row("F", st.pstdev)) + " \\\\",
            "$F$ median & " + " & ".join(stat_row("F", st.median)) + " \\\\",
            "\\midrule",
            "$C$ mean & " + " & ".join(stat_row("C", st.mean)) + " \\\\",
            "$C$ std & " + " & ".join(stat_row("C", st.pstdev)) + " \\\\",
            "$C$ median & " + " & ".join(stat_row("C", st.median)) + " \\\\",
            "\\bottomrule", "\\end{tabular}",
            "\\caption{\\textbf{Faithfulness ($F$, higher is better) and completeness ($C$, lower is better) as a function of "
            "circuit size $n$}, aggregated over the 16 prompts (population std). Per-prompt values for every $n\\in[1,50]$ are in the released repository.}",
            "\\label{tab:circuit-grid}", "\\end{table*}", ""]
    (out / "circuit_curves_tables.tex").write_text("\n".join(tex))

    md += ["", "| n | " + " | ".join(map(str, GRID)) + " |", "|---|" + "--:|" * len(GRID)]
    md.append("| F mean | " + " | ".join(f"{st.mean(r['F'][n] for r in rows):.3f}" for n in GRID) + " |")
    md.append("| C mean | " + " | ".join(f"{st.mean(r['C'][n] for r in rows):.3f}" for n in GRID) + " |")
    (out / "circuit_curves_tables.md").write_text("\n".join(md) + "\n")
    print("wrote to", out)


if __name__ == "__main__":
    main()
